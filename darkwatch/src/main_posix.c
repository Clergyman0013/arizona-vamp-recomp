/**
 * Darkwatch (Xbox, 2005) - recompiled host entry point (macOS / Linux)
 *
 * The Windows build uses src/main_win32.c instead; this file is compiled on
 * POSIX hosts and drives the same runtime:
 *
 *   1. locate the extracted game data (default.xbe + *.pck)
 *   2. map the Xbox address space and copy the XBE image into it
 *   3. bring up the kernel replacement layer and the kernel bridge
 *   4. hand control to the recompiled entry point
 *
 * It also installs a signal-based crash reporter: recompiled guest code
 * faults as ordinary native code, so the host register file (g_eax ...) plus
 * a scan of the simulated guest stack is what identifies the guest function
 * that died.
 */

